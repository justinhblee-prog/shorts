"""Workspace-scoped, fail-closed source-media asset storage.

Uploads are accepted only after bounded streaming, byte-level ffprobe inspection,
and an explicit clean malware-scan result. Browser filenames and MIME types are
metadata only; storage paths are generated by the server and never returned.
"""
from __future__ import annotations

import hashlib
import json
import math
import os
import re
import sqlite3
import tempfile
import uuid
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path

from media_inspection import MediaInspector, MediaInspectionError
from media_scanner import ClamAVScanner, MediaScanError


_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$")
_MAX_SUPPORTED_BYTES = 2 * 1024 * 1024 * 1024
_MAX_DURATION_SECONDS = 60 * 60
_MAX_DIMENSION = 8192
_CHUNK_BYTES = 1024 * 1024
_SUPPORTED_FORMATS = {"mp4", "mov", "m4a", "3gp", "3g2", "mj2"}


class MediaAssetError(RuntimeError):
    """Base class for safe media-asset failures."""


class MediaAssetRejected(MediaAssetError):
    """The submitted file or its metadata did not satisfy the media policy."""


class MediaAssetUnavailable(MediaAssetError):
    """A required scanner, inspector, or storage capability is unavailable."""


class MediaAssetStore:
    def __init__(
        self,
        db_path=None,
        media_dir=None,
        max_bytes=None,
        retention_days=None,
        scanner=None,
        inspector=None,
        scan_enabled=None,
    ):
        self.db_path = str(db_path or os.getenv("NEXUS_DB_PATH", "data/nexus.sqlite3"))
        Path(self.db_path).parent.mkdir(parents=True, exist_ok=True)

        configured_root = Path(
            media_dir or os.getenv("NEXUS_MEDIA_DIR", "data/media")
        ).expanduser()
        if configured_root.is_symlink():
            raise MediaAssetUnavailable("Media storage root must not be a symlink")
        configured_root.mkdir(parents=True, exist_ok=True)
        self.media_root = configured_root.resolve()
        self.asset_root = self.media_root / "assets"
        if self.asset_root.is_symlink():
            raise MediaAssetUnavailable("Media asset root must not be a symlink")
        self.asset_root.mkdir(parents=True, exist_ok=True)
        self.asset_root = self.asset_root.resolve()
        if self.asset_root.parent != self.media_root:
            raise MediaAssetUnavailable("Media asset root escaped the configured media directory")

        raw_max_bytes = (
            max_bytes if max_bytes is not None
            else os.getenv("NEXUS_MAX_MEDIA_BYTES", str(256 * 1024 * 1024))
        )
        try:
            self.max_bytes = int(raw_max_bytes)
        except (TypeError, ValueError) as exc:
            raise ValueError("max_bytes must be a positive integer no larger than 2 GiB") from exc
        if not 1 <= self.max_bytes <= _MAX_SUPPORTED_BYTES:
            raise ValueError("max_bytes must be a positive integer no larger than 2 GiB")

        raw_retention = (
            retention_days if retention_days is not None
            else os.getenv("NEXUS_MEDIA_ASSET_RETENTION_DAYS", "30")
        )
        try:
            self.retention_days = int(raw_retention)
        except (TypeError, ValueError) as exc:
            raise ValueError("retention_days must be between 1 and 3650") from exc
        if not 1 <= self.retention_days <= 3650:
            raise ValueError("retention_days must be between 1 and 3650")

        if scan_enabled is None:
            raw_scan = os.getenv("NEXUS_MEDIA_SCAN_ENABLED", "false").strip().lower()
            if raw_scan in {"1", "true", "yes", "on"}:
                scan_enabled = True
            elif raw_scan in {"0", "false", "no", "off", ""}:
                scan_enabled = False
            else:
                raise ValueError("NEXUS_MEDIA_SCAN_ENABLED must be an explicit boolean")
        self.scan_enabled = bool(scan_enabled)
        self.scanner = scanner or ClamAVScanner(max_bytes=self.max_bytes)
        self.inspector = inspector or MediaInspector(analyze_signals=False)
        self._initialize()

    @contextmanager
    def db(self):
        connection = sqlite3.connect(self.db_path, timeout=30, isolation_level=None)
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA foreign_keys=ON")
        connection.execute("PRAGMA busy_timeout=30000")
        try:
            yield connection
        except Exception:
            if connection.in_transaction:
                connection.rollback()
            raise
        finally:
            connection.close()

    def _initialize(self):
        with self.db() as connection:
            connection.executescript("""
                CREATE TABLE IF NOT EXISTS media_assets (
                    asset_id TEXT PRIMARY KEY,
                    workspace_id TEXT NOT NULL
                        REFERENCES workspaces(id) ON DELETE RESTRICT,
                    filename TEXT NOT NULL,
                    storage_relpath TEXT NOT NULL UNIQUE,
                    size_bytes INTEGER NOT NULL CHECK(size_bytes > 0),
                    sha256 TEXT NOT NULL CHECK(length(sha256) = 64),
                    format_names_json TEXT NOT NULL,
                    duration_seconds REAL NOT NULL CHECK(duration_seconds > 0),
                    width INTEGER NOT NULL CHECK(width > 0),
                    height INTEGER NOT NULL CHECK(height > 0),
                    video_codec TEXT NOT NULL,
                    audio_codec TEXT,
                    scan_status TEXT NOT NULL CHECK(scan_status = 'clean'),
                    created_at TEXT NOT NULL,
                    retention_until TEXT NOT NULL,
                    status TEXT NOT NULL DEFAULT 'active'
                        CHECK(status IN ('active','quarantined','deleted')),
                    UNIQUE(workspace_id, sha256)
                );
                CREATE INDEX IF NOT EXISTS idx_media_assets_workspace_created
                    ON media_assets(workspace_id, status, created_at DESC, asset_id);
            """)

    @staticmethod
    def _workspace_id(value):
        if not isinstance(value, str) or not _ID.fullmatch(value):
            raise MediaAssetRejected("A valid authenticated workspace ID is required")
        return value

    @staticmethod
    def _filename(value):
        raw = value if isinstance(value, str) else ""
        name = raw.replace("\\", "/").split("/")[-1]
        name = "".join(
            character for character in name
            if ord(character) >= 32 and ord(character) != 127
        )
        name = name.strip(" .")[:128]
        return name or "video"

    def _workspace_dir(self, workspace_id, create=False):
        workspace_id = self._workspace_id(workspace_id)
        namespace = hashlib.sha256(workspace_id.encode("utf-8")).hexdigest()
        directory = self.asset_root / namespace
        if directory.is_symlink():
            raise MediaAssetUnavailable("Workspace media directory must not be a symlink")
        if create:
            directory.mkdir(parents=True, exist_ok=True)
        if directory.exists():
            resolved = directory.resolve()
            if resolved.parent != self.asset_root:
                raise MediaAssetUnavailable("Workspace media directory escaped the asset root")
            return resolved
        return directory

    @staticmethod
    def _probe_values(probe, total_bytes):
        if not isinstance(probe, dict) or probe.get("status") != "inspected":
            raise MediaAssetRejected("Media inspection did not produce a valid report")
        try:
            size_bytes = int(probe.get("size_bytes"))
            duration = float(probe.get("duration_seconds"))
            width = int(probe.get("width"))
            height = int(probe.get("height"))
        except (TypeError, ValueError, OverflowError) as exc:
            raise MediaAssetRejected("Media has invalid size, duration, or dimensions") from exc
        if size_bytes != total_bytes:
            raise MediaAssetRejected("Media probe size does not match the uploaded bytes")
        if not math.isfinite(duration) or not 0 < duration <= _MAX_DURATION_SECONDS:
            raise MediaAssetRejected("Media duration must be between 0 and 3600 seconds")
        if not 0 < width <= _MAX_DIMENSION or not 0 < height <= _MAX_DIMENSION:
            raise MediaAssetRejected("Media dimensions exceed the supported 8192-pixel limit")
        format_names = probe.get("format_names")
        if (
            not isinstance(format_names, list)
            or not any(str(name).lower() in _SUPPORTED_FORMATS for name in format_names)
        ):
            raise MediaAssetRejected("Media container is not a supported MP4-family format")
        video_codec = probe.get("video_codec")
        if not isinstance(video_codec, str) or not video_codec.strip():
            raise MediaAssetRejected("Media video codec is missing")
        audio_codec = probe.get("audio_codec")
        if audio_codec is not None and not isinstance(audio_codec, str):
            raise MediaAssetRejected("Media audio codec metadata is invalid")
        return {
            "size_bytes": size_bytes,
            "duration_seconds": duration,
            "width": width,
            "height": height,
            "format_names": [str(name).lower() for name in format_names],
            "video_codec": video_codec,
            "audio_codec": audio_codec,
        }

    @staticmethod
    def _metadata(row, duplicate=False):
        return {
            "asset_id": row["asset_id"],
            "workspace_id": row["workspace_id"],
            "filename": row["filename"],
            "size_bytes": row["size_bytes"],
            "sha256": row["sha256"],
            "format_names": json.loads(row["format_names_json"]),
            "duration_seconds": row["duration_seconds"],
            "duration_ms": int(round(row["duration_seconds"] * 1000)),
            "width": row["width"],
            "height": row["height"],
            "video_codec": row["video_codec"],
            "audio_codec": row["audio_codec"],
            "scan_status": row["scan_status"],
            "created_at": row["created_at"],
            "retention_until": row["retention_until"],
            "status": row["status"],
            "duplicate": bool(duplicate),
        }

    def create_from_stream(self, stream, *, workspace_id, filename=None):
        """Stream one upload into a private workspace directory and register it atomically."""
        workspace_id = self._workspace_id(workspace_id)
        if not self.scan_enabled:
            raise MediaAssetUnavailable(
                "Malware scanning is disabled; source-media uploads are fail-closed"
            )
        if not hasattr(stream, "read"):
            raise MediaAssetRejected("Upload stream is invalid")

        directory = self._workspace_dir(workspace_id, create=True)
        temporary = None
        destination = None
        digest = hashlib.sha256()
        total = 0
        try:
            try:
                stream.seek(0)
            except (AttributeError, OSError):
                pass
            with tempfile.NamedTemporaryFile(
                mode="wb", dir=directory, prefix=".nexus-asset-", suffix=".part",
                delete=False,
            ) as output:
                temporary = Path(output.name)
                while True:
                    try:
                        chunk = stream.read(_CHUNK_BYTES)
                    except OSError as exc:
                        raise MediaAssetRejected("Uploaded media stream could not be read") from exc
                    if not chunk:
                        break
                    if not isinstance(chunk, (bytes, bytearray)):
                        raise MediaAssetRejected("Uploaded media stream returned non-binary data")
                    total += len(chunk)
                    if total > self.max_bytes:
                        raise MediaAssetRejected("Uploaded media exceeds NEXUS_MAX_MEDIA_BYTES")
                    digest.update(chunk)
                    output.write(chunk)
                output.flush()
                os.fsync(output.fileno())

            if total <= 0:
                raise MediaAssetRejected("Uploaded media is empty")
            if temporary.is_symlink() or not temporary.is_file():
                raise MediaAssetRejected("Temporary media must be a regular non-symlink file")

            try:
                probe = self.inspector.inspect(temporary)
            except MediaInspectionError as exc:
                message = str(exc)
                if any(token in message.lower() for token in (
                    "not installed", "could not be executed", "exceeded its inspection timeout",
                )):
                    raise MediaAssetUnavailable("Media inspection is unavailable; upload was not stored") from exc
                raise MediaAssetRejected("Uploaded file failed MP4 media inspection") from exc
            inspected = self._probe_values(probe, total)

            try:
                scan_result = self.scanner.scan(temporary)
            except MediaScanError as exc:
                if "infected" in str(exc).lower():
                    raise MediaAssetRejected("Malware scanner rejected the uploaded media") from exc
                raise MediaAssetUnavailable(
                    "Malware scanner did not complete; upload was not stored"
                ) from exc
            except Exception as exc:
                raise MediaAssetUnavailable(
                    "Malware scanner failed; upload was not stored"
                ) from exc
            if not isinstance(scan_result, dict) or scan_result.get("status") != "clean":
                raise MediaAssetUnavailable(
                    "Malware scanner did not explicitly confirm a clean upload"
                )

            sha256 = digest.hexdigest()
            safe_filename = self._filename(filename)
            created_at = datetime.now(timezone.utc)
            retention_until = created_at + timedelta(days=self.retention_days)
            asset_id = "asset_" + uuid.uuid4().hex
            destination = directory / (asset_id + ".media")
            if destination.exists() or destination.is_symlink():
                raise MediaAssetUnavailable("Generated media asset path already exists")
            relative_path = destination.relative_to(self.media_root).as_posix()

            with self.db() as connection:
                connection.execute("BEGIN IMMEDIATE")
                existing = connection.execute(
                    "SELECT * FROM media_assets WHERE workspace_id=? AND sha256=? AND status='active'",
                    (workspace_id, sha256),
                ).fetchone()
                if existing is not None:
                    connection.commit()
                    return self._metadata(existing, duplicate=True)

                os.replace(str(temporary), str(destination))
                temporary = None
                try:
                    connection.execute("""
                        INSERT INTO media_assets (
                            asset_id,workspace_id,filename,storage_relpath,size_bytes,
                            sha256,format_names_json,duration_seconds,width,height,
                            video_codec,audio_codec,scan_status,created_at,retention_until,status
                        ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,'active')
                    """, (
                        asset_id, workspace_id, safe_filename, relative_path,
                        inspected["size_bytes"], sha256,
                        json.dumps(inspected["format_names"], separators=(",", ":")),
                        inspected["duration_seconds"], inspected["width"], inspected["height"],
                        inspected["video_codec"], inspected["audio_codec"], "clean",
                        created_at.isoformat(timespec="seconds"),
                        retention_until.isoformat(timespec="seconds"),
                    ))
                    connection.commit()
                except Exception:
                    if connection.in_transaction:
                        connection.rollback()
                    try:
                        destination.unlink(missing_ok=True)
                    except OSError:
                        pass
                    raise
                row = connection.execute(
                    "SELECT * FROM media_assets WHERE asset_id=? AND workspace_id=?",
                    (asset_id, workspace_id),
                ).fetchone()
                if row is None:
                    raise MediaAssetUnavailable("Media asset registration could not be verified")
                return self._metadata(row, duplicate=False)
        except sqlite3.IntegrityError as exc:
            raise MediaAssetRejected("Workspace media asset registration conflicted") from exc
        finally:
            if temporary is not None:
                try:
                    temporary.unlink(missing_ok=True)
                except OSError:
                    pass

    def get(self, asset_id, *, workspace_id):
        workspace_id = self._workspace_id(workspace_id)
        if not isinstance(asset_id, str) or not re.fullmatch(r"asset_[a-f0-9]{32}", asset_id):
            return None
        with self.db() as connection:
            row = connection.execute(
                "SELECT * FROM media_assets WHERE asset_id=? AND workspace_id=? AND status='active'",
                (asset_id, workspace_id),
            ).fetchone()
        return self._metadata(row) if row is not None else None

    def list_for_workspace(self, workspace_id, limit=50):
        workspace_id = self._workspace_id(workspace_id)
        if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= 100:
            raise ValueError("asset list limit must be between 1 and 100")
        with self.db() as connection:
            rows = connection.execute(
                "SELECT * FROM media_assets WHERE workspace_id=? AND status='active' "
                "ORDER BY created_at DESC,asset_id DESC LIMIT ?",
                (workspace_id, limit),
            ).fetchall()
        return [self._metadata(row) for row in rows]

    def resolve_path(self, asset_id, *, workspace_id):
        """Resolve a private asset for a future renderer; never expose this path via HTTP."""
        workspace_id = self._workspace_id(workspace_id)
        if not isinstance(asset_id, str) or not re.fullmatch(r"asset_[a-f0-9]{32}", asset_id):
            return None
        with self.db() as connection:
            row = connection.execute(
                "SELECT storage_relpath FROM media_assets "
                "WHERE asset_id=? AND workspace_id=? AND status='active'",
                (asset_id, workspace_id),
            ).fetchone()
        if row is None:
            return None
        workspace_dir = self._workspace_dir(workspace_id, create=False).resolve()
        candidate = self.media_root / row["storage_relpath"]
        if candidate.is_symlink():
            raise MediaAssetUnavailable("Stored media asset must not be a symlink")
        resolved = candidate.resolve()
        if not resolved.is_relative_to(workspace_dir) or not resolved.is_file():
            raise MediaAssetUnavailable("Stored media asset is missing or outside its workspace")
        return resolved
